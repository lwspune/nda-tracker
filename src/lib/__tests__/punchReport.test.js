import { describe, it, expect } from 'vitest'
import {
  parsePunchSheet,
  reportTimes,
  matchPunchRows,
  ATTENDANCE_REPORT_BRANCH,
  NOT_PUNCHED_IN,
  NOT_PUNCHED_OUT,
  ABSENT,
} from '../punchReport'

// The shape of EIS's "Punch Monitor" export, as downloaded on 23 Oct 2026:
// a title row, a header row, one row per student, then a blank row and two
// footer lines.
const HEADER = ['Sr. No.', 'Reg No.', 'Name', 'Role', 'Batch', 'Recent Punch', 'In Time', 'Out Time', 'Att Status']
const sheet = (...rows) => [
  [' Punch_Monitor_list_23 Oct 2026', '', '', '', '', '', '', '', ''],
  HEADER,
  ...rows,
  ['', '', '', '', '', '', '', '', ''],
  ['Note : Total 3 records available in this file & exported on Fri Oct 23 21:05:00 IST 2026', '', '', '', '', '', '', '', ''],
  ['This Report is generated by EISDigital.com- MANAGE, ANALYZE and GROW your Institute', '', '', '', '', '', '', '', ''],
]
const row = (sr, reg, name, inT, outT, status, recent = inT || 'N/A') =>
  [sr, reg, name, 'Student', '11&12th Integrated 2-Year (25-27) - A', recent, inT, outT, status]

describe('parsePunchSheet', () => {
  it('reads the report date from the title row, not from today', () => {
    expect(parsePunchSheet(sheet()).date).toBe('2026-10-23')
  })

  it('returns a null date when the title carries none', () => {
    const m = sheet()
    m[0] = ['Punch Monitor', '', '']
    expect(parsePunchSheet(m).date).toBeNull()
  })

  it('reads every student row and skips the blank and footer rows', () => {
    const { rows } = parsePunchSheet(sheet(
      row(1, '250522204', 'Sanmod Jambagi', '', '', 'A'),
      row(2, '250629576', 'Arjun Bhayegave', '10:34 AM', '06:10 PM', 'P'),
    ))
    expect(rows).toEqual([
      { regNo: '250522204', name: 'Sanmod Jambagi', batch: '11&12th Integrated 2-Year (25-27) - A', status: 'A', inTime: '', outTime: '' },
      { regNo: '250629576', name: 'Arjun Bhayegave', batch: '11&12th Integrated 2-Year (25-27) - A', status: 'P', inTime: '10:34 AM', outTime: '06:10 PM' },
    ])
  })

  // The notebook this replaces read column 5 ("Recent Punch") as the out time.
  // A student who punched once then showed In 10:34, Out 10:34.
  it('takes the out time from the Out Time column, never Recent Punch', () => {
    const { rows } = parsePunchSheet(sheet(row(1, '250629576', 'Arjun', '10:34 AM', '', 'P', '10:34 AM')))
    expect(rows[0].outTime).toBe('')
  })

  it('finds columns by header, so a reordered export still reads correctly', () => {
    const m = [
      ['Punch_Monitor_list_23 Oct 2026'],
      ['Att Status', 'Out Time', 'In Time', 'Name', 'Reg No.', 'Sr. No.'],
      ['P', '06:00 PM', '08:30 AM', 'Asha', '260101001', 1],
    ]
    expect(parsePunchSheet(m).rows[0]).toMatchObject({
      regNo: '260101001', name: 'Asha', status: 'P', inTime: '08:30 AM', outTime: '06:00 PM',
    })
  })

  it('throws, naming the column, when a required column is missing', () => {
    const m = sheet()
    m[1] = HEADER.filter(h => h !== 'Out Time')
    expect(() => parsePunchSheet(m)).toThrow(/Out Time/)
  })

  it('throws when there is no header row at all', () => {
    expect(() => parsePunchSheet([['hello'], ['world']])).toThrow(/Reg No/)
  })

  it('turns a numeric registration number into its digits', () => {
    const { rows } = parsePunchSheet(sheet(row(1, 250522204, 'Sanmod', '', '', 'A')))
    expect(rows[0].regNo).toBe('250522204')
  })

  it('cleans non-breaking and doubled spaces out of names', () => {
    const { rows } = parsePunchSheet(sheet(row(1, '250731667', 'Amaan  Ausaf  Ansari', '', '', 'A')))
    expect(rows[0].name).toBe('Amaan Ausaf Ansari')
  })

  // The 23 Oct file listed 260510737 twice. Sending both would message the
  // family twice.
  it('keeps the first row of a repeated registration number and reports it', () => {
    const { rows, duplicates } = parsePunchSheet(sheet(
      row(1, '260510737', 'Vedant', '08:30 AM', '', 'P'),
      row(2, '260510737', 'Vedant', '', '', 'A'),
    ))
    expect(rows).toHaveLength(1)
    expect(rows[0].status).toBe('P')
    expect(duplicates).toEqual(['260510737'])
  })

  it('upper-cases the status', () => {
    expect(parsePunchSheet(sheet(row(1, '1', 'A', '', '', 'a'))).rows[0].status).toBe('A')
  })
})

describe('reportTimes', () => {
  it('says Absent for both times when the student was absent', () => {
    expect(reportTimes({ status: 'A', inTime: '', outTime: '' })).toEqual({ inText: ABSENT, outText: ABSENT })
  })

  it('says Absent even if an absent row somehow carries a time', () => {
    expect(reportTimes({ status: 'A', inTime: '09:00 AM', outTime: '' })).toEqual({ inText: ABSENT, outText: ABSENT })
  })

  it('passes both punch times through for a present student', () => {
    expect(reportTimes({ status: 'P', inTime: '08:35 AM', outTime: '06:10 PM' }))
      .toEqual({ inText: '08:35 AM', outText: '06:10 PM' })
  })

  it('says Not punched out when a present student has no out time', () => {
    expect(reportTimes({ status: 'P', inTime: '08:35 AM', outTime: '' }))
      .toEqual({ inText: '08:35 AM', outText: NOT_PUNCHED_OUT })
    expect(NOT_PUNCHED_OUT).toBe('Not punched out')
  })

  it('says Not punched in when a present student has no in time', () => {
    expect(reportTimes({ status: 'P', inTime: '', outTime: '06:10 PM' }).inText).toBe(NOT_PUNCHED_IN)
  })

  // These strings go into a WhatsApp template variable. Anything that is not a
  // plain clock time is dropped rather than forwarded to a parent.
  it('treats anything that is not a clock time as missing', () => {
    expect(reportTimes({ status: 'P', inTime: 'N/A', outTime: '<b>6</b>' }))
      .toEqual({ inText: NOT_PUNCHED_IN, outText: NOT_PUNCHED_OUT })
  })

  it('normalises the clock time it passes through', () => {
    expect(reportTimes({ status: 'P', inTime: ' 8:05 am', outTime: '06:10PM' }))
      .toEqual({ inText: '8:05 AM', outText: '06:10 PM' })
  })
})

describe('matchPunchRows', () => {
  const student = (over = {}) => ({
    lws_id: 'LWS-1', canonical_name: 'Arjun Bhayegave', eis_reg_no: '250629576',
    branch: ATTENDANCE_REPORT_BRANCH, account_status: 'Active',
    mobile: '9876543210', parent_mobiles: ['9876543211'], ...over,
  })
  const punch = (over = {}) => ({
    regNo: '250629576', name: 'Arjun Vitthal Bhayegave', batch: 'B', status: 'P',
    inTime: '10:34 AM', outTime: '06:10 PM', ...over,
  })

  it('is scoped to LWS Pune', () => {
    expect(ATTENDANCE_REPORT_BRANCH).toBe('LWS Pune')
  })

  it("matches on the EIS registration number and uses the tracker's name and numbers", () => {
    const { ready } = matchPunchRows([punch()], [student()])
    expect(ready).toEqual([{
      lwsId: 'LWS-1', name: 'Arjun Bhayegave', regNo: '250629576', status: 'P',
      inTime: '10:34 AM', outTime: '06:10 PM', inText: '10:34 AM', outText: '06:10 PM',
      mobile: '9876543210', parentMobiles: ['9876543211'],
    }])
  })

  it('lists a registration number the tracker does not know, and does not send it', () => {
    const r = matchPunchRows([punch({ regNo: '261021118', name: 'Shravani Vedpathak' })], [student()])
    expect(r.ready).toEqual([])
    expect(r.unmatched).toEqual([expect.objectContaining({ regNo: '261021118', name: 'Shravani Vedpathak' })])
  })

  it('excludes a student from another branch', () => {
    const r = matchPunchRows([punch()], [student({ branch: 'APJ' })])
    expect(r.ready).toEqual([])
    expect(r.otherBranch).toHaveLength(1)
  })

  it('excludes a blocked student and lists them', () => {
    const r = matchPunchRows([punch()], [student({ account_status: 'Block' })])
    expect(r.ready).toEqual([])
    expect(r.blocked).toHaveLength(1)
  })

  // Two tracker records claiming one registration number is a data problem;
  // picking one would message the wrong family half the time.
  it('refuses to guess when two students share a registration number', () => {
    const r = matchPunchRows([punch()], [student(), student({ lws_id: 'LWS-2', canonical_name: 'Other' })])
    expect(r.ready).toEqual([])
    expect(r.unmatched[0].reason).toMatch(/2 students/)
  })

  it('ignores students with a blank registration number', () => {
    const r = matchPunchRows([punch({ regNo: '' })], [student({ eis_reg_no: '' })])
    expect(r.ready).toEqual([])
  })

  it('falls back to the file name when the tracker record has none', () => {
    const { ready } = matchPunchRows([punch()], [student({ canonical_name: '' })])
    expect(ready[0].name).toBe('Arjun Vitthal Bhayegave')
  })
})
